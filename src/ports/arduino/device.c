/**
 * @brief Get the platform BACnet object table
 *
 * Returns a pointer to the BACnet object table implemented by
 * the current platform port.
 *
 * @return Pointer to the first entry of the object table.
 *
 * @note The returned table must remain valid for the lifetime
 *       of the application.
 */
object_functions_t* get_Port_Object_Table(void)
{ 
    return &My_Port_Object_Table[0];
}


